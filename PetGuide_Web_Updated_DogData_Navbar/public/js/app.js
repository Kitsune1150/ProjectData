// ==========================================
// 1. Helper Functions (ฟังก์ชันช่วยเหลือทั่วไป)
// ==========================================

function getToken() {
  return localStorage.getItem("token");
}

function getUser() {
  try {
    const u = localStorage.getItem("user");
    return u ? JSON.parse(u) : null;
  } catch {
    return null;
  }
}

function escapeHtml(str) {
  if (!str) return "";
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function safeUrl(url) {
  const fallback = "https://images.unsplash.com/photo-1543466835-00a7907e9de1?auto=format&fit=crop&w=900&q=80";
  if (!url) return fallback;
  try {
    const parsed = new URL(String(url), location.origin);
    if (parsed.protocol === "https:") return parsed.href;
    if (parsed.origin === location.origin && parsed.pathname.startsWith("/images/")) {
      return parsed.pathname + parsed.search + parsed.hash;
    }
  } catch {
    // Use the fallback for invalid image URLs.
  }
  return fallback;
}

// ==========================================
// 2. API Call Functions (ฟังก์ชันเชื่อมต่อ Server)
// ==========================================

async function api(url, options = {}) {
  const token = getToken();
  const headers = {
    "Content-Type": "application/json",
    ...(token ? { Authorization: "Bearer " + token } : {}),
    ...options.headers,
  };

  const res = await fetch(url, { ...options, headers });
  const responseText = await res.text();
  let data = {};
  try {
    data = responseText ? JSON.parse(responseText) : {};
  } catch {
    data = {};
  }

  if (!res.ok) {
    const message = data.message || (
      res.status === 404 && url.includes("/api/admin/upload-image")
        ? "ไม่พบ API อัปโหลดรูปภาพ กรุณารีสตาร์ทเซิร์ฟเวอร์ด้วย npm run dev แล้วลองใหม่"
        : res.status === 413
          ? "ไฟล์ใหญ่เกินขนาดที่เซิร์ฟเวอร์รับได้ กรุณาเลือกรูปที่เล็กลง"
          : `เซิร์ฟเวอร์ตอบกลับ HTTP ${res.status}`
    );
    alert(message);
    const error = new Error(message);
    error.status = res.status;
    error.alerted = true;
    throw error;
  }
  return data;
}

async function fetchJSON(url) {
  return api(url);
}

